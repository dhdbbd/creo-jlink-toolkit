param(
  [Parameter(Mandatory=$true)][string[]]$Model,
  [string]$Type = 'asm',
  [string]$ModelDir = 'C:\models',
  [string]$OutDir = (Join-Path $env:USERPROFILE 'Desktop'),
  [string]$Profile = (Join-Path $PSScriptRoot '..\profiles\ap242.dep_step'),
  [int]$TimeoutSec = 1200
)
$ErrorActionPreference = 'Stop'
$work = (Join-Path $PSScriptRoot '..\work')

if (-not (Test-Path -LiteralPath $Profile)) { throw ('profile not found: ' + $Profile) }
if (-not (Test-Path -LiteralPath $ModelDir)) { throw ('model dir not found: ' + $ModelDir) }
if (-not (Test-Path -LiteralPath $OutDir)) { New-Item -ItemType Directory -Path $OutDir | Out-Null }

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('# generated by export_ap242.ps1  ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'))
$lines.Add('# profile: ' + $Profile)
$lines.Add('DIR|' + $ModelDir)
foreach ($m in $Model) {
  $out = Join-Path $OutDir ($m.ToUpper() + '_AP242')
  $lines.Add('EXPORT|' + $m + '|' + $Type + '|' + $out + '|' + $Profile)
}
[System.IO.File]::WriteAllText((Join-Path $work 'export_job.txt'), (($lines -join "`r`n") + "`r`n"), (New-Object System.Text.UTF8Encoding($false)))

Write-Output '--- job ---'
$lines | ForEach-Object { Write-Output ('  ' + $_) }
Write-Output '--- run ---'
& powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $PSScriptRoot 'spawn_sync_export.ps1') -TimeoutSec $TimeoutSec |
  Where-Object { $_ -match 'job \d+/\d+|plaintext size|HEADER:|ProIntf3DFileWrite|SYNC_EXPORT_DONE|done=|starting xtop|\.stp' } |
  ForEach-Object { Write-Output $_ }
